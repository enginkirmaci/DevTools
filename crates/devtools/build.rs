use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    // Windows only: embed the app icon so Explorer, shortcuts and the taskbar
    // show the mark. The winresource build-dep is windows-gated, so this block
    // must vanish on every other host.
    #[cfg(target_os = "windows")]
    {
        println!("cargo:rerun-if-changed=../../packaging/windows/devtools.ico");
        let mut res = winresource::WindowsResource::new();
        res.set_icon("../../packaging/windows/devtools.ico");
        if let Err(err) = res.compile() {
            panic!("could not embed Windows resources: {err}");
        }
    }

    embed_assets();
}

// This used to be rust-embed, which silently drops every file whose
// std::fs::canonicalize fails (filter_map + ok()?). Mapped/subst Windows
// volumes can fail exactly that call for every path (os error 1005) while
// plain reads keep working - the embedded set then comes out empty and the
// UI runs without any icons. Generate the table with plain filesystem reads
// instead: include_bytes! needs no canonicalization. Absolute paths are
// required because the generated file lives in OUT_DIR.
fn embed_assets() {
    let manifest_dir =
        PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let assets_dir = manifest_dir.join("assets");
    println!("cargo:rerun-if-changed={}", assets_dir.display());

    let mut files = Vec::new();
    collect(&assets_dir, &assets_dir, &mut files);
    files.sort();
    if files.is_empty() {
        panic!(
            "no assets found under {} - refusing to build with an empty asset set",
            assets_dir.display()
        );
    }

    let mut generated =
        String::from("// generated by build.rs from the assets/ tree - do not edit\n");
    generated.push_str("static EMBEDDED_FILES: &[(&str, &[u8])] = &[\n");
    for (key, path) in &files {
        writeln!(
            generated,
            "    ({key:?}, include_bytes!({path:?})),",
            path = path.display().to_string()
        )
        .unwrap();
    }
    generated.push_str("];\n");

    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    fs::write(out_dir.join("embedded_assets.rs"), generated).expect("write embedded_assets.rs");
}

fn collect(root: &Path, dir: &Path, files: &mut Vec<(String, PathBuf)>) {
    let mut entries: Vec<_> = fs::read_dir(dir)
        .unwrap_or_else(|err| panic!("could not read {}: {err}", dir.display()))
        .filter_map(Result::ok)
        .collect();
    entries.sort_by_key(|entry| entry.file_name());
    for entry in entries {
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, files);
        } else {
            // keys are relative to assets/ with forward slashes, matching the
            // paths the UI passes to AssetSource::load
            let key = path
                .strip_prefix(root)
                .expect("strip assets prefix")
                .to_string_lossy()
                .replace('\\', "/");
            files.push((key, path));
        }
    }
}
